import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),target=new URL('public/world/surface-data.js',root);
const manifest=JSON.parse(await readFile(new URL('docs/SURFACES.json',root),'utf8'));
const sha=b=>createHash('sha256').update(b).digest('hex');
export async function prepareSurfaces(){
 try{const cached=await readFile(target);if(sha(cached)===manifest.generatedSha256)return;}catch{}
 const maps={};
 for(const item of manifest.assets){
  const url=new URL(item.url);if(url.protocol!=='https:'||!['dl.polyhaven.org','dl.polyhaven.com'].includes(url.hostname))throw Error('Unapproved surface source');
  const res=await fetch(url,{signal:AbortSignal.timeout(45000)});if(!res.ok)throw Error(`Material fetch ${res.status}: ${item.id}`);
  const bytes=Buffer.from(await res.arrayBuffer());if(sha(bytes)!==item.sha256)throw Error(`Material checksum mismatch: ${item.id}/${item.map}`);
  maps[item.id]??={};maps[item.id][item.map]=`data:image/${/\.jpe?g$/i.test(url.pathname)?'jpeg':'png'};base64,${bytes.toString('base64')}`;
 }
 const source='// CC0 material maps. Generated by scripts/fetch-surfaces.mjs; see docs/SURFACES.json.\nexport const SURFACES='+JSON.stringify(maps)+';\n';
 if(sha(source)!==manifest.generatedSha256)throw Error('Generated surfaces differ from pinned artifact');
 await mkdir(new URL('public/world/',root),{recursive:true});await writeFile(target,source);
}
await prepareSurfaces();
